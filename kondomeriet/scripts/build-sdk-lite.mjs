// node kondomeriet/scripts/build-sdk-lite.mjs <path to a vio-web-sdk checkout>
// Rebuilds kondomeriet/vio-sdk/sdk-lite.js from the SDK's source (see sdk-lite-entry.ts).
// Its version is the SDK checkout's; commit the result with the SDK commit in the message.
import path from "path";
import fs from "fs";
import { execSync } from "child_process";
import { fileURLToPath } from "url";
const sdk = path.resolve(process.argv[2] || "../vio-web-sdk");
const here = path.dirname(fileURLToPath(import.meta.url));
const { build } = await import(path.join(sdk, "node_modules/esbuild/lib/main.js"));
const out = path.join(here, "../vio-sdk/sdk-lite.js");
await build({
  entryPoints: [path.join(here, "sdk-lite-entry.ts")],
  bundle: true,
  format: "esm",
  target: ["es2020"],
  outfile: out,
  alias: { "@sdk": path.join(sdk, "src") },
  minify: false,
  legalComments: "none",
  logLevel: "warning",
});
const sha = (() => {
  try {
    return execSync(`git -C "${sdk}" rev-parse --short HEAD`).toString().trim();
  } catch {
    return "?";
  }
})();
// esbuild's per-file comments carry the local path of the SDK checkout: keep only the SDK-relative part.
const body = fs.readFileSync(out, "utf8").replace(/^\/\/ .*?\/src\/(.+)$/gm, "// vio-web-sdk/src/$1");
fs.writeFileSync(out, `// GENERATED by kondomeriet/scripts/build-sdk-lite.mjs from vio-web-sdk (${sha}). Do not edit.\n` + body);
console.log("sdk-lite.js:", Math.round(body.length / 1024), "KB");

// The SDK product detail's stylesheet as text (its `static styles`, one lit `css` block with no
// interpolations): the Kondomeriet product info draws with it, in its own shadow root.
{
  const src = fs.readFileSync(path.join(sdk, "src/ui/components/vio-product-detail.ts"), "utf8");
  const start = src.indexOf("static override styles = [");
  const open = src.indexOf("css`", start);
  const close = src.indexOf("`", open + 4);
  if (start < 0 || open < 0 || close < 0) throw new Error("vio-product-detail styles not found");
  const css = src.slice(open + 4, close);
  if (css.includes("${")) throw new Error("vio-product-detail styles have interpolations: update the extractor");
  const min = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s+/g, " ").trim();
  const file = path.join(here, "../vio-sdk/detail-css.js");
  fs.writeFileSync(
    file,
    `// GENERATED by kondomeriet/scripts/build-sdk-lite.mjs from vio-web-sdk (${sha}) src/ui/components/vio-product-detail.ts. Do not edit.\nexport const SDK_DETAIL_CSS = ${JSON.stringify(min)};\n`
  );
  console.log("detail-css.js:", Math.round(min.length / 1024), "KB");
}
